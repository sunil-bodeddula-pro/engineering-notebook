#!/usr/bin/env python3
"""Copy assets/style.css, assets/viz.js and assets/favicon.svg into every page, so each HTML file works on its own,
fill in the shared footer from assets/footer.html, and build the menus from assets/nav.json.

Run from the site/ folder after editing anything in assets/:

    python3 tools/inline_assets.py          # rewrite the pages
    python3 tools/inline_assets.py --check  # exit 1 if any page is out of date (no writes)

Each page keeps its copy between the markers
    <!-- inline-assets:start ... -->  and  <!-- inline-assets:end -->
and its footer between
    <!-- site-footer:start ... -->  and  <!-- site-footer:end -->
({root} in footer.html becomes the relative path back to the site root: "" for top-level pages,
"../" for patterns/, ai/, system-design/, architecture/, behavioural/ and lld/, "../../" for ai/{modules,cases}/, system-design/{modules,designs}/ architecture/{modules,cases}/, behavioural/modules/ and lld/{modules,problems}/.)
and its menus (top bar = the tracks, left sidebar = the current track's pages) between
    <!-- site-chrome:start ... -->  and  <!-- site-chrome:end -->
A page's track comes from <body data-track="…"> (no attribute = "coding").
"""
import glob
import html as htmllib
import json
import os
import re
import sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START = "<!-- inline-assets:start (generated by tools/inline_assets.py from assets/) -->"
END = "<!-- inline-assets:end -->"
FOOT_START = "<!-- site-footer:start (generated by tools/inline_assets.py from assets/footer.html) -->"
FOOT_END = "<!-- site-footer:end -->"
CHROME_START = "<!-- site-chrome:start (generated by tools/inline_assets.py from assets/nav.json) -->"
CHROME_END = "<!-- site-chrome:end -->"
BRAND = '<span class="brand-mark" aria-hidden="true"></span><span class="brand-word">Interview<b>Kata</b></span>'


def pattern_items():
    """[label, path] for every pattern page, labelled "NN · <h1 text>"."""
    out = []
    for rel in sorted(glob.glob(os.path.join("patterns", "*.html"), root_dir=ROOT)):
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            m = re.search(r"<h1>(.*?)</h1>", f.read(), re.S)
        title = htmllib.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else rel
        out.append([f"{os.path.basename(rel)[:2]} · {title}", rel.replace(os.sep, "/")])
    return out


def chrome(path, page_html, nav):
    """Top bar with the tracks, plus the left sidebar for this page's track."""
    rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
    root = "../" * rel.count("/")
    body = re.search(r"<body\b[^>]*>", page_html[page_html.find("</head>"):])
    tm = re.search(r'data-track="([^"]+)"', body.group(0)) if body else None
    track_id = tm.group(1) if tm else "coding"
    esc = lambda t: htmllib.escape(t, quote=False)
    tabs = []
    for t in nav["tracks"]:
        if t.get("soon"):
            tabs.append(f'<span class="track-soon" title="Coming soon">{esc(t["label"])} <small>soon</small></span>')
        else:
            cur = ' aria-current="true"' if t["id"] == track_id else ""
            # "tab" is an optional shorter name for the top bar, so six tracks fit; the sidebar title keeps "label".
            tip = f' title="{esc(t["label"])}"' if t.get("tab") else ""
            tabs.append(f'<a href="{root}{t["home"]}"{cur}{tip}>{esc(t.get("tab", t["label"]))}</a>')
    tabs = "".join(tabs)
    track = next(t for t in nav["tracks"] if t["id"] == track_id)
    groups = []
    for g in track["groups"]:
        items = pattern_items() if g.get("auto") == "patterns" else g["items"]
        links, here = [], False
        for label, target in items:
            file = target.split("#")[0]
            if not os.path.exists(os.path.join(ROOT, file)):
                links.append(f'<span class="sn-soon">{esc(label)} <small>soon</small></span>')
                continue
            cur = file == rel and "#" not in target
            here = here or cur
            links.append(f'<a href="{root}{target}"{" aria-current=\"page\"" if cur else ""}>{esc(label)}</a>')
        if g["title"] == "Get started":
            groups.append(f'<div class="sn-group"><div class="sn-h">{esc(g["title"])}</div>{"".join(links)}</div>')
        else:
            groups.append(f'<details class="sn-group"{" open" if here else ""}><summary>{esc(g["title"])}</summary>{"".join(links)}</details>')
    return (f"{CHROME_START}\n"
            f'<header class="topbar">\n'
            f'  <a class="brand" href="{root}index.html">{BRAND}</a>\n'
            f'  <nav class="tracks" aria-label="Tracks">{tabs}</nav>\n'
            f'  <span class="spacer"></span>\n'
            f'  <button class="search-btn" type="button" data-root="{root}" aria-label="Search the site" title="Search (press /)"><svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><circle cx="11" cy="11" r="7" fill="none" stroke="currentColor" stroke-width="2.2"/><path d="m16.5 16.5 4.5 4.5" stroke="currentColor" stroke-width="2.2" stroke-linecap="round"/></svg><span class="search-btn-label">Search</span><kbd>/</kbd></button>\n'
            f'  <button class="nav-toggle" type="button" aria-controls="sidenav" aria-expanded="false"><span class="nav-toggle-icon" aria-hidden="true"></span><span class="nav-toggle-label">Menu</span></button>\n'
            f"</header>\n"
            f'<nav class="sidenav" id="sidenav" aria-label="{esc(track["label"])}">\n'
            f'  <div class="sn-tracks">{tabs}</div>\n'
            f'  <a class="sn-title" href="{root}{track["home"]}">{esc(track["label"])}</a>\n'
            f'  {"".join(groups)}\n'
            f"</nav>\n"
            f'<div class="sn-scrim" aria-hidden="true"></div>\n'
            f"{CHROME_END}")


def footer(path):
    with open(os.path.join(ROOT, "assets", "footer.html"), encoding="utf-8") as f:
        tpl = f.read().strip()
    depth = os.path.relpath(path, ROOT).count(os.sep)
    root = "../" * depth
    return f"{FOOT_START}\n{tpl.replace('{root}', root)}\n{FOOT_END}"


def block():
    with open(os.path.join(ROOT, "assets", "style.css"), encoding="utf-8") as f:
        css = f.read()
    with open(os.path.join(ROOT, "assets", "viz.js"), encoding="utf-8") as f:
        js = f.read()
    with open(os.path.join(ROOT, "assets", "favicon.svg"), encoding="utf-8") as f:
        svg = " ".join(f.read().split())
    # A data: URI, so the tab icon also shows when a page is opened on its own.
    icon = f'<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,{quote(svg, safe=" =:/\',.-")}">'
    # Web fonts are an online enhancement: offline, the system fonts in style.css take over.
    fonts = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
             '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
             '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400..700;1,9..144,400..600'
             '&family=Inter:wght@400..700&family=JetBrains+Mono:wght@400..700&display=swap">')
    return f"{START}\n{icon}\n{fonts}\n<style>\n{css.rstrip()}\n\n</style>\n<script>\n{js.rstrip()}\n</script>\n{END}"


def pages():
    names = ["index.html", "start-here.html", "cheatsheet.html", "review.html", "google.html", "meta.html", "nvidia.html", "amazon.html", "microsoft.html", "apple.html", "cisco.html", "netflix.html"] + sorted(glob.glob(os.path.join("patterns", "*.html"), root_dir=ROOT))
    names += sorted(glob.glob(os.path.join("ai", "*.html"), root_dir=ROOT)) + sorted(glob.glob(os.path.join("ai", "modules", "*.html"), root_dir=ROOT)) + sorted(glob.glob(os.path.join("ai", "cases", "*.html"), root_dir=ROOT))
    for d in ("system-design", os.path.join("system-design", "modules"), os.path.join("system-design", "designs"), "architecture", os.path.join("architecture", "modules"), os.path.join("architecture", "cases"), "behavioural", os.path.join("behavioural", "modules"), "lld", os.path.join("lld", "modules"), os.path.join("lld", "problems"), "styles", os.path.join("styles", "modules")):
        names += sorted(glob.glob(os.path.join(d, "*.html"), root_dir=ROOT))
    return [os.path.join(ROOT, n) for n in names]


def main():
    check = "--check" in sys.argv
    new_block = block()
    with open(os.path.join(ROOT, "assets", "nav.json"), encoding="utf-8") as f:
        nav = json.load(f)
    stale = []
    for path in pages():
        with open(path, encoding="utf-8") as f:
            html = f.read()
        a = html.find(START)
        b = html.find(END)
        if a < 0 or b < 0:
            sys.exit(f"{os.path.relpath(path, ROOT)}: inline-assets markers not found")
        updated = html[:a] + new_block + html[b + len(END):]
        fa = updated.find(FOOT_START)
        fb = updated.find(FOOT_END)
        if fa < 0 or fb < 0:
            sys.exit(f"{os.path.relpath(path, ROOT)}: site-footer markers not found")
        updated = updated[:fa] + footer(path) + updated[fb + len(FOOT_END):]
        ca = updated.find(CHROME_START)
        cb = updated.find(CHROME_END)
        if ca < 0 or cb < 0:
            sys.exit(f"{os.path.relpath(path, ROOT)}: site-chrome markers not found")
        updated = updated[:ca] + chrome(path, updated, nav) + updated[cb + len(CHROME_END):]
        if updated != html:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(updated)
    if check:
        print("out of date: " + ", ".join(stale) if stale else "all pages up to date")
        sys.exit(1 if stale else 0)
    print(f"updated {len(stale)} page(s)" if stale else "all pages already up to date")


if __name__ == "__main__":
    main()
