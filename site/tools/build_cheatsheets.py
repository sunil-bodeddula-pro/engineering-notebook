def build(track, nav):
    t = next(x for x in nav["tracks"] if x["id"] == track)
    body, toc, n = [], [], 0
    for g in t["groups"]:
        if g["title"] == "Get started" or "items" not in g:
            continue
        cards = []
        for label, target in g["items"]:
            path = os.path.join(ROOT, target.split("#")[0])
            if not os.path.exists(path) or target.endswith("index.html"):
                continue
            c = card(open(path, encoding="utf-8").read())
            if not c:
                continue
            hook, hook_text, rows = c
            num, _, title = label.partition(" · ")
            if not title:
                num, title = "", label
            href = os.path.relpath(path, os.path.join(ROOT, track))
            dl = "".join(f"<dt>{esc(k)}</dt><dd>" + (esc(v[0]) if len(v) == 1 else "<ul>" + "".join(f"<li>{esc(x)}</li>" for x in v) + "</ul>") + "</dd>" for k, v in rows if v)
            cards.append(f'    <div class="card"><span class="n">{esc(num)}</span><h3><a href="{href}">{esc(title)}</a></h3>'
                         + (f'<p class="hk">“{esc(hook)}”</p><p class="ht">{esc(hook_text)}</p>' if hook else "")
                         + (f"<dl>{dl}</dl>" if dl else "") + "</div>")
        if cards:
            gid = "g-" + re.sub(r"[^a-z0-9]+", "-", g["title"].lower()).strip("-")
            toc.append(f'\n      <li><a href="#{gid}">{esc(g["title"])}</a></li>')
            body.append(f'    <h2 id="{gid}">{esc(g["title"])}</h2>\n    <div class="sheet">\n' + "\n".join(cards) + "\n    </div>")
            n += len(cards)
    label = TRACKS[track]
    what = {"system-design": "module and worked design", "lld": "module and problem", "architecture": "module and case study"}.get(track, "module")
    desc = f"Cheat sheet for the {label} track: every {what} on one printable page, with its memory hook and key points."
    out = (PAGE.replace("__STYLE__", STYLE).replace("__LABEL__", esc(label)).replace("__DESC__", esc(desc)).replace("__TRACK__", track)
           .replace("__TOC__", "".join(toc)).replace("__WHAT__", what).replace("__BODY__", "\n".join(body)))
    return out, n


def main():
    check, stale = "--check" in sys.argv, []
    nav = json.load(open(os.path.join(ROOT, "assets", "nav.json"), encoding="utf-8"))
    for track in TRACKS:
        if not any(x["id"] == track and not x.get("soon") for x in nav["tracks"]):
            continue
        out, n = build(track, nav)
        rel = f"{track}/cheatsheet.html"
        if not pagegen.write_or_check(rel, out, check):
            stale.append(rel)
        if not check:
            print(f"{rel}: {n} cards")
    if check:
        print("cheat sheets: up to date" if not stale else "cheat sheets: stale: " + ", ".join(stale))
        sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
