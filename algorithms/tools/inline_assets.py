#!/usr/bin/env python3
"""Copy assets/style.css, assets/viz.js and assets/favicon.svg into every page, so each HTML file works on its own,
and fill in the shared footer from assets/footer.html.

Run from the algorithms/ folder after editing anything in assets/:

    python3 tools/inline_assets.py          # rewrite the pages
    python3 tools/inline_assets.py --check  # exit 1 if any page is out of date (no writes)

Each page keeps its copy between the markers
    <!-- inline-assets:start ... -->  and  <!-- inline-assets:end -->
and its footer between
    <!-- site-footer:start ... -->  and  <!-- site-footer:end -->
({root} in footer.html becomes "" for top-level pages and "../" for pattern pages.)
"""
import glob
import os
import sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START = "<!-- inline-assets:start (generated by tools/inline_assets.py from assets/) -->"
END = "<!-- inline-assets:end -->"
FOOT_START = "<!-- site-footer:start (generated by tools/inline_assets.py from assets/footer.html) -->"
FOOT_END = "<!-- site-footer:end -->"


def footer(path):
    with open(os.path.join(ROOT, "assets", "footer.html"), encoding="utf-8") as f:
        tpl = f.read().strip()
    root = "../" if os.path.basename(os.path.dirname(path)) == "patterns" else ""
    return f"{FOOT_START}\n{tpl.replace('{root}', root)}\n{FOOT_END}"


def block():
    with open(os.path.join(ROOT, "assets", "style.css"), encoding="utf-8") as f:
        css = f.read()
    with open(os.path.join(ROOT, "assets", "viz.js"), encoding="utf-8") as f:
        js = f.read()
    with open(os.path.join(ROOT, "assets", "favicon.svg"), encoding="utf-8") as f:
        svg = " ".join(f.read().split())
    # A data: URI, so the tab icon also shows when a page is opened on its own.
    icon = f'<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,{quote(svg, safe=" =:/\',.-")}">'
    return f"{START}\n{icon}\n<style>\n{css.rstrip()}\n\n</style>\n<script>\n{js.rstrip()}\n</script>\n{END}"


def pages():
    names = ["index.html", "start-here.html", "cheatsheet.html", "google.html", "meta.html", "nvidia.html", "amazon.html", "microsoft.html", "apple.html", "cisco.html", "netflix.html"] + sorted(glob.glob(os.path.join("patterns", "*.html")))
    return [os.path.join(ROOT, n) for n in names]


def main():
    check = "--check" in sys.argv
    new_block = block()
    stale = []
    for path in pages():
        with open(path, encoding="utf-8") as f:
            html = f.read()
        a = html.find(START)
        b = html.find(END)
        if a < 0 or b < 0:
            sys.exit(f"{os.path.relpath(path, ROOT)}: inline-assets markers not found")
        updated = html[:a] + new_block + html[b + len(END):]
        fa = updated.find(FOOT_START)
        fb = updated.find(FOOT_END)
        if fa < 0 or fb < 0:
            sys.exit(f"{os.path.relpath(path, ROOT)}: site-footer markers not found")
        updated = updated[:fa] + footer(path) + updated[fb + len(FOOT_END):]
        if updated != html:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(updated)
    if check:
        print("out of date: " + ", ".join(stale) if stale else "all pages up to date")
        sys.exit(1 if stale else 0)
    print(f"updated {len(stale)} page(s)" if stale else "all pages already up to date")


if __name__ == "__main__":
    main()
